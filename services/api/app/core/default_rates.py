def get_supported_regions() -> List[Dict[str, Any]]:
    return list(SUPPORTED_REGIONS.values())


def get_default_catalogue(
    region: str = "national_cpwd",
    category: Optional[str] = None,
    material_group: Optional[str] = None,
    search: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """
    Returns the core material rate catalogue with regional pricing applied for the requested region.
    Strictly filters to materials only; zero labour or equipment items returned.
    """
    reg = region if region in SUPPORTED_REGIONS else "national_cpwd"
    results = []

    for item in DEFAULT_RATE_CATALOG_ITEMS:
        # Strictly ensure material category only
        if item.get("category") != "material":
            continue

        if category and category != "all" and item.get("category") != category:
            continue

        if material_group and material_group != "all" and item.get("material_group") != material_group:
            continue

        if search and search.strip():
            term = search.strip().lower()
            code = item.get("code", "").lower()
            name = item.get("name", "").lower()
            spec = item.get("specification", "").lower()
            desc = item.get("description", "").lower()
            if term not in code and term not in name and term not in spec and term not in desc:
                continue

        # Extract regional rates
        reg_rate = item.get("regional_rates", {}).get(reg, {})
        mat_rate = reg_rate.get("material", Decimal("0.00"))
        lab_rate = reg_rate.get("labour", Decimal("0.00"))
        eqp_rate = reg_rate.get("equipment", Decimal("0.00"))
        comb_rate = mat_rate + lab_rate + eqp_rate

        cloned = {
            "code": item["code"],
            "name": item["name"],
            "category": item["category"],
            "material_group": item.get("material_group", "other_materials"),
            "rate_type": item["rate_type"],
            "unit": item["unit"],
            "specification": item.get("specification"),
            "description": item.get("description"),
            "material_rate": mat_rate,
            "labour_rate": lab_rate,
            "equipment_rate": eqp_rate,
            "combined_rate": comb_rate,
            "rate_source": item.get("rate_source", "Schedule of Rates"),
            "supplier_or_source_name": item.get("supplier_or_source_name"),
            "source_date": item.get("source_date"),
            "rate_status": item.get("rate_status", "verified_source"),
            "region": reg,
            "notes": item.get("notes"),
        }
        results.append(cloned)

    return results


def find_default_item_by_code(code: str, region: str = "national_cpwd") -> Optional[Dict[str, Any]]:
    items = get_default_catalogue(region=region)
    for it in items:
        if it["code"] == code:
            return it
    return None
